#!/usr/bin/env node
/**
 * Runs after every `astro build`. Reads the prerendered OEmbedCard
 * fragment (src/pages/oembed-card.html.astro) astro build just wrote,
 * writes its HTML into src/generated/oembedCard.ts as a plain string
 * constant, and removes the fragment from dist/client so nothing is
 * actually served at /oembed-card.html/.
 *
 * oembed.json.ts imports that constant instead of rendering the
 * component per request. Because this script runs after the same build
 * that bundles oembed.json.ts, a change to OEmbedCard.astro or the site
 * metadata it renders (src/site.ts) needs one more `npm run build` to
 * reach the constant.
 */

import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FRAGMENT_DIR = resolve(ROOT, 'dist/client/oembed-card.html');
const OUT = resolve(ROOT, 'src/generated/oembedCard.ts');

const html = (await readFile(resolve(FRAGMENT_DIR, 'index.html'), 'utf8')).trim();

await mkdir(dirname(OUT), { recursive: true });
await writeFile(
  OUT,
  '// Generated by scripts/render-oembed-card.mjs from src/components/OEmbedCard.astro.\n' +
    '// Do not edit by hand — run `npm run build` again to regenerate.\n' +
    `export const OEMBED_CARD_HTML = ${JSON.stringify(html)};\n`,
);

await rm(FRAGMENT_DIR, { recursive: true, force: true });
